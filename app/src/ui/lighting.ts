//   반지름은 12°까지: 16°면 책 그림자 빛 길이 구간(physShadow.bands) 경계가 47DU로 책 깊이 안에 들어와 책을 0.5DU 밀 때 벽 그림자가 0.5 튄다(book-cast 테스트)
// - 방 빛: 위(천장)가 가장 밝고 보는 사람 쪽(앞)도 밝은 방(ambient 0.5, skyTilt (0, 0.29, −0.15)): 앞을 보는 면 0.65, 위를 보는 면 0.79, 옆을 보는 면 0.5.
//   그림자 참고 그림은 판 윗면이 앞면보다 밝고 책 머리도 밝다(위에서 드는 빛): 판 윗면 / 앞면 0.61 → 0.86, 맨 윗줄 책 머리 0.61 → 0.85.
//   창빛 0.42: 가장 진한 그림자 ≈ 0.65 / (0.65 + 0.42 × 0.97) ≈ 0.61(화면에서 보이는 곳은 0.7 안팎, 시안 0.72~0.79·판 아래 0.56~0.77)
// - 빛 색: 창빛은 흰빛, 방 빛은 살짝 따뜻하다([1.14, 1, 0.84]). 창빛이 가려진 그늘은 방 빛만 받아 밝은 곳보다 빨강/초록 약 1.06배·파랑/초록 0.93배
//   (그림자 참고 그림 범위, 황갈색. 1차 B안의 [1.48, 1, 0.83]은 그늘이 주황이었다). 방 빛이 가려지지 않으니 같은 그늘은 어디서나 같은 색이다
// 세기는 상대값이다. 재질 색(시안 색)은 그 재질이 대표 자리에서 보이는 색으로 보고 반사율을 거꾸로 구한다
