// Individual silhouettes measured on the 941 × 1672 reference. Background,
// neighbouring books and cast shadows are excluded. This is sample artwork only;
// registered books continue to use their own art, typography and geometry.
import type { Pose, ReferenceArt } from './types';

const DU = 390 / 941;
type XY = [number, number];

function art(pose: Pose, points: XY[], lean = 0): ReferenceArt {
  const t = -lean * Math.PI / 180;
  const a = Math.cos(t), b = Math.sin(t), c = -b, d = a;
  const turned = points.map(([x, y]) => ({ x: a * x + c * y, y: b * x + d * y }));
  const x0 = Math.min(...turned.map((p) => p.x));
  const y0 = Math.min(...turned.map((p) => p.y));
  return {
    pose,
    width: (Math.max(...turned.map((p) => p.x)) - x0) * DU,
    height: (Math.max(...turned.map((p) => p.y)) - y0) * DU,
    outline: turned.map((p) => ({ x: (p.x - x0) * DU, y: (p.y - y0) * DU })),
    matrix: [a * DU, b * DU, c * DU, d * DU, -x0 * DU, -y0 * DU],
  };
}

