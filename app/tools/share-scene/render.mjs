// 공유 카드 장면을 CanvasKit(앱과 같은 Skia)으로 그린다: node --experimental-strip-types render.mjs <cover.jpg> <out.png> [json 입력]
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
import path from 'path';
import { fileURLToPath } from 'url';
const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const CanvasKitInit = require(APP + '/node_modules/canvaskit-wasm/bin/full/canvaskit.js');
const { JsiSkApi } = require(APP + '/node_modules/@shopify/react-native-skia/lib/commonjs/skia/web/JsiSkia.js');
const scene = await import(APP + '/src/features/book/share-scene.ts');
const CK = await CanvasKitInit({ locateFile: (f) => APP + '/node_modules/canvaskit-wasm/bin/full/' + f });
const Skia = JsiSkApi(CK);
const img = (p) => Skia.Image.MakeImageFromEncoded(Skia.Data.fromBytes(new Uint8Array(fs.readFileSync(p))));
const tf = (p) => Skia.Typeface.MakeFreeTypeFaceFromData(Skia.Data.fromBytes(new Uint8Array(fs.readFileSync(p))));
const ASSET = process.env.ASSET || APP + '/assets/share';
const fonts = Skia.TypefaceFontProvider.Make();
fonts.registerFont(tf(APP + '/assets/fonts/MaruBuri-SemiBold.ttf'), 'ShareTitle');
fonts.registerFont(tf(APP + '/assets/fonts/MaruBuri-Regular.ttf'), 'ShareNote');
fonts.registerFont(tf(APP + '/assets/fonts/Pretendard-Regular.otf'), 'ShareUI');
fonts.registerFont(tf(APP + '/assets/fonts/Pretendard-Medium.otf'), 'ShareUIMedium');
const [coverPath, out, json] = process.argv.slice(2);
const cover = coverPath && coverPath !== '-' ? img(coverPath) : null;
const input = Object.assign({ title: '아몬드', author: '손원평', note: '조금 천천히,\n내 기준으로 살아가기.', rating: 4.5, coverAspect: cover ? cover.width() / cover.height() : 0.703, thicknessRatio: 0.07 }, json ? JSON.parse(json) : {});
const A = { plate: img(ASSET + '/plate.png'), mul: img(ASSET + '/book-mul.png'), add: img(ASSET + '/book-add.png'), pages: img(ASSET + '/book-pages.png'), shelfRight: img(ASSET + '/shelf-right.png'), shelfFront: img(ASSET + '/shelf-front.png'), cover, fonts };
const L = scene.layoutShareScene(Skia, input, fonts);
const W = 941, H = Math.round(L.height * W / 941);
const surf = Skia.Surface.Make(W, H);
const c = surf.getCanvas();
scene.drawShareScene(Skia, c, W, L, A, input);
surf.flush();
fs.writeFileSync(out, Buffer.from(surf.makeImageSnapshot().encodeToBytes()));
console.log('wrote', out, W, H, JSON.stringify({ cover: L.cover, pageW: L.pageW }));
