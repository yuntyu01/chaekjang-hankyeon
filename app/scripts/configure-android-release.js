#!/usr/bin/env node

/**
 * This script appends a release signing config to the android/app/build.gradle produced by `expo prebuild`.
 * Prebuild wires the release build type to the debug keystore, so the block below overrides it with the
 * upload keystore passed through environment variables, and fails the build early when any of them is missing.
 * Run it after prebuild and before `./gradlew bundleRelease`.
 */

const fs = require("fs");
const path = require("path");

const buildGradlePath = path.join(process.cwd(), "android", "app", "build.gradle");
const marker = "FORCE_RELEASE_SIGNING_CONFIG";

let source = fs.readFileSync(buildGradlePath, "utf8");

if (source.includes(marker)) {
  console.log("⏩ Release signing config already present, skipping.");
  process.exit(0);
}

const releaseSigningConfig = `

// --- ${marker} ---
// Overrides the signingConfigs.release block generated by Expo prebuild.
android {
    signingConfigs {
        release {
            def storeFilePath = System.getenv("STORE_FILE")
            if (storeFilePath != null) {
                storeFile file(storeFilePath)
                storePassword System.getenv("KEYSTORE_PASSWORD")
                keyAlias System.getenv("KEY_ALIAS")
                keyPassword System.getenv("KEY_PASSWORD")
            }
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.release
        }
    }
}

// Fail before any release task runs instead of shipping a debug signed bundle.
gradle.taskGraph.whenReady { taskGraph ->
    if (!taskGraph.allTasks.any { it.name.toLowerCase().contains("release") }) {
        return
    }

    def missing = ["STORE_FILE", "KEYSTORE_PASSWORD", "KEY_ALIAS", "KEY_PASSWORD"].findAll {
        !System.getenv(it)
    }

    if (!missing.isEmpty()) {
        throw new GradleException("Missing Android release signing env vars: \${missing.join(', ')}")
    }
}
// ------------------------------------
`;

fs.writeFileSync(buildGradlePath, source + releaseSigningConfig);

console.log("✅ Appended release signing config to android/app/build.gradle");
